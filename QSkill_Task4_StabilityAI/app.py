import streamlit as st
from src.speech import transcribe_audio
from src.stability_client import generate_image
from src.config import get_api_key

st.set_page_config(page_title="Voice2Vision AI", page_icon="🎙️", layout="wide")

st.title("🎙️ Voice2Vision AI")
st.caption("Turn spoken ideas into AI-generated images using speech recognition and Stability AI.")

with st.sidebar:
    st.header("Settings")
    language_options = {
        "English (India)": "en-IN",
        "English (US)": "en-US",
        "Hindi": "hi-IN",
        "Kannada": "kn-IN",
        "Tamil": "ta-IN",
        "Telugu": "te-IN",
        "Malayalam": "ml-IN",
        "Bengali": "bn-IN",
        "Marathi": "mr-IN",
        "Spanish": "es-ES",
        "French": "fr-FR",
        "German": "de-DE",
    }
    selected_language = st.selectbox("Spoken language", list(language_options.keys()))
    st.caption("Select the language you will speak. Speech recognition needs internet access.")
    st.divider()
    st.caption("Your API key is loaded from .env and is not shown.")

left, right = st.columns(2, gap="large")

with left:
    st.subheader("1. Record your idea")
    audio = st.audio_input("Record audio", sample_rate=16000)
    st.caption("Speak clearly for a few seconds. You can also type a prompt below.")

    if audio is not None:
        st.audio(audio)
        if st.button("Convert speech to text", type="primary", use_container_width=True):
            with st.spinner("Recognizing your speech..."):
                try:
                    recognized = transcribe_audio(audio.getvalue(), language_options[selected_language])
                    st.session_state["recognized_transcript"] = recognized
                except Exception as exc:
                    st.error(f"Speech recognition failed: {exc}")

    st.subheader("2. Review your prompt")
    prompt = st.text_area(
        "Recognized text (editable)",
        value=st.session_state.get("recognized_transcript", ""),
        height=140,
        placeholder="Speak or type your image description here.",
        key="prompt_editor",
    )
    st.caption("For better results, describe the subject, setting, style, lighting and mood.")

with right:
    st.subheader("3. Generate image")
    negative_prompt = st.text_input(
        "Negative prompt (optional)",
        value="blurry, low quality, distorted, watermark, text",
    )
    aspect_options = {
        "Square (1:1)": "1:1",
        "Portrait (2:3)": "2:3",
        "Landscape (16:9)": "16:9",
        "Wide (3:2)": "3:2",
    }
    aspect_label = st.selectbox("Image aspect ratio", list(aspect_options.keys()))

    if st.button("✨ Generate image with Stability AI", type="primary", use_container_width=True):
        if not prompt.strip():
            st.warning("Record speech or type a prompt first.")
        elif not get_api_key():
            st.error("API key not found. Add STABILITY_API_KEY to your .env file.")
        else:
            try:
                with st.spinner("Generating your image with Stability AI... This may take a little while."):
                    image_bytes = generate_image(
                        prompt=prompt.strip(),
                        negative_prompt=negative_prompt.strip(),
                        aspect_ratio=aspect_options[aspect_label],
                    )
                st.session_state["generated_image"] = image_bytes
                st.success("Image generated successfully!")
            except Exception as exc:
                st.error(f"Image generation failed: {exc}")

    generated = st.session_state.get("generated_image")
    if generated:
        st.image(generated, caption="Generated by Stability AI", use_container_width=True)
        st.download_button(
            "Download generated image",
            data=generated,
            file_name="voice2vision_generated.png",
            mime="image/png",
            use_container_width=True,
        )

st.divider()
st.markdown(
    "**Workflow:** Browser microphone → speech recognition → editable prompt → "
    "Stability AI Stable Image Core → generated image."
)
